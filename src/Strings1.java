public class Strings1 {
    public static void main(String[] args) {
        String str="Sheryar";
        int length=str.length();
        System.out.println(length+" --> First Method");

        System.out.println(str.length()+" -->Second Method");

        System.out.println("SheryarAhmad".length()+"  -->Third Method");

        int length1="SheheryarAhmad".length();
        System.out.println(length1+"  -->Fourth Method");
    }
}
